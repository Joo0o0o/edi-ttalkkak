function raw({ shoulder = 1.234, pelvis = -0.812, left = 12, right = 10, height = 0.0085, xs = [-0.21, 0.2, -0.15, 0.17] } = {}) {
  return {
    shoulderInfo: { angle_xy: shoulder, moireCountLeft: left, moireCountRight: right, verticalDistanceDiff: height, pointLeft: { camera: { x: xs[0] } }, pointRight: { camera: { x: xs[1] } } },
    pelvisInfo: { angle_xy: pelvis, pointLeft: { camera: { x: xs[2] } }, pointRight: { camera: { x: xs[3] } } }
  };
}

function temoText(options) { return temo.moireMetrics(raw(options)).copy_text; }

